export interface Descriptor {
  readonly description: string;
  /** The name a reader would give the line, or null when no name can be recovered. */
  readonly expected: string | null;
  readonly kind: "readable" | "code" | "processor";
}

const r = (description: string, expected: string): Descriptor => ({
  description,
  expected,
  kind: "readable",
});
const code = (description: string): Descriptor => ({
  description,
  expected: null,
  kind: "code",
});
const p = (description: string, expected: string | null): Descriptor => ({
  description,
  expected,
  kind: "processor",
});

